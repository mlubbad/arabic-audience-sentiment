import { PGlite } from "@electric-sql/pglite";
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
  existsSync,
} from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const snapshotPath = resolve(root, "supabase/schema/current.sql");
const check = process.argv.includes("--check");

const bootstrap = `
  create role anon;
  create role authenticated;
  create role service_role bypassrls;
  create schema auth;
  create table auth.users(
    id uuid primary key,
    email text,
    created_at timestamptz not null default now(),
    last_sign_in_at timestamptz
  );
  create function auth.uid() returns uuid language sql stable
    as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  grant usage on schema auth to authenticated, anon;
  grant execute on function auth.uid() to authenticated, anon;
  create schema storage;
  create table storage.buckets(
    id text primary key,
    name text,
    public boolean,
    file_size_limit bigint,
    allowed_mime_types text[]
  );
  create table storage.objects(
    id uuid primary key default gen_random_uuid(),
    bucket_id text,
    name text
  );
  alter table storage.objects enable row level security;
  grant usage on schema storage to authenticated;
  grant select, insert, update, delete on storage.objects to authenticated;
`;

async function applyMigrations(db) {
  await db.exec(bootstrap);
  for (const file of readdirSync(resolve(root, "supabase/migrations"))
    .filter((name) => name.endsWith(".sql"))
    .sort()) {
    await db.exec(
      readFileSync(resolve(root, "supabase/migrations", file), "utf8"),
    );
  }
}

async function rows(db, text) {
  const result = await db.query(text);
  return result.rows;
}

function quoteIdent(identifier) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function quoteLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

async function dumpSchema(db) {
  const output = [
    "-- Generated by scripts/snapshot-schema.mjs; do not edit by hand.",
    "-- Regenerate with: npm run db:snapshot",
    "",
  ];

  const schemas = await rows(
    db,
    `select nspname as name
       from pg_namespace
      where nspname not like 'pg_%'
        and nspname <> 'information_schema'
      order by nspname`,
  );
  for (const schema of schemas) {
    output.push(`create schema if not exists ${quoteIdent(schema.name)};`, "");
  }

  const tables = await rows(
    db,
    `select n.nspname as schema_name, c.relname as table_name,
            case c.relkind when 'v' then 'view' when 'm' then 'materialized view'
                 else 'table' end as kind,
            case when c.relrowsecurity then ' enabled' else '' end as rls
       from pg_class c
       join pg_namespace n on n.oid = c.relnamespace
      where c.relkind in ('r', 'p', 'v', 'm')
        and n.nspname not like 'pg_%'
        and n.nspname <> 'information_schema'
      order by n.nspname, c.relname`,
  );
  for (const table of tables) {
    const relation = `${quoteIdent(table.schema_name)}.${quoteIdent(table.table_name)}`;
    const columns = await rows(
      db,
      `select a.attname as name,
              pg_catalog.format_type(a.atttypid, a.atttypmod) as type,
              pg_get_expr(d.adbin, d.adrelid) as default_value,
              a.attnotnull as not_null
         from pg_attribute a
         join pg_class c on c.oid = a.attrelid
         join pg_namespace n on n.oid = c.relnamespace
         left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
        where a.attrelid = '${table.schema_name}.${table.table_name}'::regclass
          and a.attnum > 0 and not a.attisdropped
        order by a.attnum`,
    );
    if (table.kind === "view" || table.kind === "materialized view") {
      const definition = await rows(
        db,
        `select pg_get_viewdef('${table.schema_name}.${table.table_name}'::regclass, true) as definition`,
      );
      output.push(
        `create ${table.kind} ${relation} as`,
        `${definition[0].definition};`,
        "",
      );
      continue;
    }
    output.push(`create table ${relation} (`);
    output.push(
      columns
        .map((column) => {
          const parts = [
            `  ${quoteIdent(column.name)} ${column.type}`,
            column.default_value ? `default ${column.default_value}` : "",
            column.not_null ? "not null" : "",
          ];
          return parts.filter(Boolean).join(" ");
        })
        .join(",\n"),
    );
    output.push(");");
    if (table.rls)
      output.push(`alter table ${relation} enable row level security;`);
    output.push("");

    const constraints = await rows(
      db,
      `select conname as name, pg_get_constraintdef(oid, true) as definition
         from pg_constraint
        where conrelid = '${table.schema_name}.${table.table_name}'::regclass
        order by conname`,
    );
    for (const constraint of constraints) {
      output.push(
        `alter table ${relation} add constraint ${quoteIdent(constraint.name)} ${constraint.definition};`,
      );
    }
    if (constraints.length) output.push("");

    const indexes = await rows(
      db,
      `select indexname, indexdef
         from pg_indexes
        where schemaname = ${quoteLiteral(table.schema_name)}
          and tablename = ${quoteLiteral(table.table_name)}
        order by indexname`,
    );
    for (const index of indexes) output.push(`${index.indexdef};`);
    if (indexes.length) output.push("");
  }

  const functions = await rows(
    db,
    `select n.nspname as schema_name, p.proname as function_name,
            p.oid::regprocedure::text as signature,
            pg_get_functiondef(p.oid) as definition
       from pg_proc p
       join pg_namespace n on n.oid = p.pronamespace
      where n.nspname not in ('pg_catalog', 'information_schema')
      order by n.nspname, p.proname, p.oid::regprocedure::text`,
  );
  for (const fn of functions) output.push(`${fn.definition.trim()}\n`);

  const policies = await rows(
    db,
    `select n.nspname as schema_name, c.relname as table_name,
            p.polname as policy_name, pg_get_expr(p.polqual, p.polrelid) as using_expr,
            pg_get_expr(p.polwithcheck, p.polrelid) as check_expr,
            array_to_string(array(
              select quote_ident(pg_get_userbyid(role_oid))
                from unnest(p.polroles) as role_oid
                order by 1
            ), ', ') as roles,
            case p.polcmd when 'r' then 'select' when 'a' then 'insert'
                 when 'w' then 'update' when 'd' then 'delete' else 'all' end as command
       from pg_policy p
       join pg_class c on c.oid = p.polrelid
       join pg_namespace n on n.oid = c.relnamespace
      order by n.nspname, c.relname, p.polname`,
  );
  for (const policy of policies) {
    const relation = `${quoteIdent(policy.schema_name)}.${quoteIdent(policy.table_name)}`;
    const usingClause = policy.using_expr
      ? ` using (${policy.using_expr})`
      : "";
    const checkClause = policy.check_expr
      ? ` with check (${policy.check_expr})`
      : "";
    const roleClause = policy.roles ? ` to ${policy.roles}` : "";
    output.push(
      `create policy ${quoteIdent(policy.policy_name)} on ${relation}${roleClause} for ${policy.command}${usingClause}${checkClause};`,
    );
  }
  if (policies.length) output.push("");

  const grants = await rows(
    db,
    `select grantee, table_schema, table_name, privilege_type
       from information_schema.role_table_grants
      where table_schema not in ('pg_catalog', 'information_schema')
      order by table_schema, table_name, grantee, privilege_type`,
  );
  for (const grant of grants) {
    output.push(
      `grant ${grant.privilege_type} on table ${quoteIdent(grant.table_schema)}.${quoteIdent(grant.table_name)} to ${quoteIdent(grant.grantee)};`,
    );
  }
  const schemaGrants = await rows(
    db,
    `select n.nspname as schema_name,
            case when grant_data.grantee = 0 then 'public'
                 else grant_data.grantee::regrole::text end as grantee,
            grant_data.privilege_type
       from pg_namespace n
       cross join lateral aclexplode(
         coalesce(n.nspacl, acldefault('n', n.nspowner))
       ) as grant_data
      where n.nspname not in ('pg_catalog', 'information_schema')
      order by n.nspname, grantee, grant_data.privilege_type`,
  );
  for (const grant of schemaGrants) {
    output.push(
      `grant ${grant.privilege_type} on schema ${quoteIdent(grant.schema_name)} to ${quoteIdent(grant.grantee)};`,
    );
  }
  const routineGrants = await rows(
    db,
    `select n.nspname as schema_name, p.oid::regprocedure::text as signature,
            case when grant_data.grantee = 0 then 'public'
                 else grant_data.grantee::regrole::text end as grantee,
            grant_data.privilege_type
       from pg_proc p
       join pg_namespace n on n.oid = p.pronamespace
       cross join lateral aclexplode(
         coalesce(p.proacl, acldefault('f', p.proowner))
       ) as grant_data
      where n.nspname not in ('pg_catalog', 'information_schema')
      order by n.nspname, p.oid::regprocedure::text,
               grantee, grant_data.privilege_type`,
  );
  for (const grant of routineGrants) {
    output.push(
      `grant ${grant.privilege_type} on function ${grant.signature} to ${quoteIdent(grant.grantee)};`,
    );
  }

  return `${output
    .join("\n")
    .replaceAll(/\n{3,}/g, "\n\n")
    .trim()}\n`;
}

async function main() {
  const db = new PGlite();
  try {
    await applyMigrations(db);
    const snapshot = await dumpSchema(db);
    if (check) {
      const current = existsSync(snapshotPath)
        ? readFileSync(snapshotPath, "utf8")
        : "";
      if (current !== snapshot) {
        process.stderr.write(
          "Schema snapshot is stale. Run `npm run db:snapshot` and review the diff.\n",
        );
        process.exitCode = 1;
      }
      return;
    }
    mkdirSync(resolve(root, "supabase/schema"), { recursive: true });
    writeFileSync(snapshotPath, snapshot);
  } finally {
    await db.close();
  }
}

await main();
